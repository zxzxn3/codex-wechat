"""Linux stable uninstall helper; Windows uses uninstall.ps1."""
import asyncio
import os
from pathlib import Path
import shutil
import sys

from . import service_adapter
from .platform_support import (CONFIG_ROOT_FILE, DATA_ROOT_FILE, INSTALL_ROOT,
                               IS_WINDOWS, STATE_ROOT_FILE, runtime_paths,
                               xdg_config_home)
from .service_control import UNIT, systemctl
from .storage import Store

UNIT_DROPIN_MARKER = "# Generated by codex-wechat installer"


def _command_link() -> Path:
    return Path.home() / ".local/bin/codex-wechat"


def _unit_link() -> Path:
    return xdg_config_home() / "systemd/user" / UNIT


def _unit_dropin() -> Path:
    return _unit_link().with_name(UNIT + ".d") / "data-root.conf"


def _remove_unit_dropin() -> None:
    path = _unit_dropin()
    if path.is_symlink():
        return
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return
    if UNIT_DROPIN_MARKER not in text:
        return
    try:
        path.unlink()
        path.parent.rmdir()
    except OSError:
        pass


def _remove_runtime_root_markers() -> None:
    for filename in (DATA_ROOT_FILE, CONFIG_ROOT_FILE, STATE_ROOT_FILE):
        try:
            (INSTALL_ROOT / filename).unlink()
        except FileNotFoundError:
            pass


def _remove_path(path: Path) -> None:
    if path.is_symlink():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


def _paths_overlap(first: Path, second: Path) -> bool:
    return first == second or first.is_relative_to(second) or second.is_relative_to(first)


async def _linux_service_removal() -> None:
    link = _unit_link()
    if not link.exists() and not link.is_symlink():
        # Installations that cannot reach a user service manager never create
        # this unit link and run in the documented foreground-only mode.
        _remove_unit_dropin()
        print("后台服务未注册；跳过服务移除。")
        return
    try:
        current = await service_adapter.status()
    except FileNotFoundError:
        # No systemd client is installed; there cannot be a registered unit.
        current = None
    except (OSError, RuntimeError) as error:
        raise RuntimeError(f"无法确认后台服务状态，拒绝卸载: {error}") from error
    except ValueError:
        print("检测到不属于本安装的后台服务，未改动该服务。")
        return
    if current is None or not current.installed:
        _remove_unit_dropin()
        return
    if current.running:
        await service_adapter.stop_and_wait()
    try:
        await systemctl("disable", UNIT)
    except (OSError, RuntimeError):
        # The unit may only have been linked for on-demand starts.
        pass
    expected = (INSTALL_ROOT / UNIT).resolve()
    try:
        owns_link = link.is_symlink() and link.resolve() == expected
    except OSError:
        owns_link = False
    if owns_link:
        link.unlink()
    _remove_unit_dropin()
    try:
        await systemctl("daemon-reload")
    except (OSError, RuntimeError):
        pass
    print("后台服务已停止并移除注册。")


def _linux_command_removal() -> None:
    link = _command_link()
    expected = (INSTALL_ROOT / "codex-wechat").resolve()
    try:
        owns_link = link.is_symlink() and link.resolve() == expected
    except OSError:
        owns_link = False
    if owns_link:
        link.unlink()
        print(f"已移除命令入口: {link}")
    elif link.exists():
        print(f"保留不是本安装创建的命令入口: {link}")


def _validated_purge_targets(paths):
    targets = (
        ("配置", paths.config_file),
        ("状态", paths.state_dir),
        ("工作区", paths.workspace_dir),
    )
    home = Path.home().resolve()
    install = INSTALL_ROOT.resolve()
    expected_workspace = (paths.data_root / "workspace").resolve()
    for role, path in targets:
        target = Path(path).expanduser().resolve()
        if target in {Path(target.anchor), home} or home.is_relative_to(target):
            raise ValueError(f"拒绝删除范围过大的数据目录: {target}")
        if role == "工作区":
            if target != expected_workspace:
                raise ValueError(f"工作区路径不在预期数据根内: {target}")
            if target == install or install.is_relative_to(target):
                raise ValueError(f"拒绝删除包含程序安装目录的工作区: {target}")
        elif _paths_overlap(target, install):
            raise ValueError(f"拒绝删除与程序安装目录重叠的{role}路径: {target}")
    return targets


def _purge_linux_data(paths=None) -> None:
    paths = runtime_paths() if paths is None else paths
    targets = _validated_purge_targets(paths)
    for _, path in targets:
        _remove_path(path)
    try:
        paths.config_file.parent.rmdir()
    except OSError:
        pass
    print("已删除配置、登录、待办、工作目录、日志和共享后台数据。")


def _require_no_bridge(state_dir: Path | None = None) -> None:
    state_dir = runtime_paths().state_dir if state_dir is None else Path(state_dir)
    if not state_dir.exists():
        return
    try:
        store = Store(state_dir)
    except RuntimeError:
        raise RuntimeError("前台桥接仍在运行，请先按 Ctrl+C 退出后再卸载。") from None
    except (OSError, ValueError) as error:
        raise RuntimeError(f"无法确认前台桥接是否已停止: {state_dir}") from error
    else:
        store.close()


async def uninstall(*, purge: bool = False) -> None:
    if IS_WINDOWS:
        raise RuntimeError("Windows 卸载请使用 stable uninstall.ps1；uninstall.py 仅用于 Linux。")
    # Validate the data-root contract before removing the service or touching
    # any user data. The stable entry checks this too, but a direct helper
    # invocation must not be able to skip the check.
    marker = INSTALL_ROOT / DATA_ROOT_FILE
    if (purge and not marker.exists() and not marker.is_symlink()
            and not os.environ.get("CODEX_WECHAT_DATA_ROOT")):
        raise RuntimeError("缺少数据根标记；拒绝在没有显式数据根时清理数据")
    paths = runtime_paths()
    if purge:
        # All destructive targets are validated before service or command
        # removal, so a bad XDG/install-root overlap leaves the install intact.
        _validated_purge_targets(paths)
    await _linux_service_removal()
    _require_no_bridge(paths.state_dir)
    _linux_command_removal()
    if purge:
        _purge_linux_data(paths)
        # Only a purge forgets the roots. A data-preserving uninstall keeps the
        # markers so the next installation resolves the same directories.
        _remove_runtime_root_markers()
    # Actions report above; this summary names what is left, in one order shared
    # with the Windows helper: program files, data, how to keep using it, then the
    # decision about removing the rest. The uninstaller runs out of the install
    # tree, so it cannot delete it itself.
    print(f"程序文件仍在: {INSTALL_ROOT}（含 releases 与 Python 环境，不含用户数据）")
    if purge:
        print(f"数据文件已删除: {paths.data_root}")
    else:
        print(f"数据文件仍在: {paths.data_root}")
        print(f"配置仍在: {paths.config_file}")
        print(f"状态仍在: {paths.state_dir}")
        print("重新运行安装器会继续使用这个数据根；如需同时删除配置、登录和待办，"
              "请使用 --purge-data。")
    print("如不再需要，可在本命令结束后手动删除上述目录。")


def main(argv=None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--purge-data",
        action="store_true",
        help="同时删除配置、登录、待办、工作目录、日志和共享后台数据",
    )
    args = parser.parse_args(argv)
    try:
        asyncio.run(uninstall(purge=args.purge_data))
    except (KeyboardInterrupt, asyncio.CancelledError):
        return 130
    except (OSError, RuntimeError, ValueError) as error:
        print(f"uninstall.py: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
