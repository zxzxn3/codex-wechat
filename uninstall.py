"""Linux stable uninstall helper; Windows uses uninstall.ps1."""
import asyncio
import os
from pathlib import Path
import shutil
import sys

import service_adapter
from platform_support import DATA_ROOT_FILE, INSTALL_ROOT, IS_WINDOWS, data_root
from service_control import UNIT, systemctl
from storage import Store

LINUX_DATA_PATHS = ("config.json", ".state", "workspace", "logs", "shared")
UNIT_DROPIN_MARKER = "# Generated by codex-wechat installer"


def _command_link() -> Path:
    return Path.home() / ".local/bin/codex-wechat"


def _unit_link() -> Path:
    config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    return config.expanduser().resolve() / "systemd/user" / UNIT


def _unit_dropin() -> Path:
    return _unit_link().with_name(UNIT + ".d") / "data-root.conf"


def _remove_unit_dropin() -> None:
    path = _unit_dropin()
    if path.is_symlink():
        return
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return
    if UNIT_DROPIN_MARKER not in text:
        return
    try:
        path.unlink()
        path.parent.rmdir()
    except OSError:
        pass


def _remove_data_root_marker() -> None:
    try:
        (INSTALL_ROOT / DATA_ROOT_FILE).unlink()
    except FileNotFoundError:
        pass


def _remove_path(path: Path) -> None:
    if path.is_symlink():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


async def _linux_service_removal() -> None:
    try:
        current = await service_adapter.status()
    except FileNotFoundError:
        # No systemd client is installed; there cannot be a registered unit.
        current = None
    except (OSError, RuntimeError) as error:
        raise RuntimeError(f"无法确认后台服务状态，拒绝卸载: {error}") from error
    except ValueError:
        print("检测到不属于本安装的后台服务，未改动该服务。")
        return
    if current is None or not current.installed:
        _remove_unit_dropin()
        return
    if current.running:
        await service_adapter.stop_and_wait()
    try:
        await systemctl("disable", UNIT)
    except (OSError, RuntimeError):
        # The unit may only have been linked for on-demand starts.
        pass
    link = _unit_link()
    expected = (INSTALL_ROOT / UNIT).resolve()
    try:
        owns_link = link.is_symlink() and link.resolve() == expected
    except OSError:
        owns_link = False
    if owns_link:
        link.unlink()
    _remove_unit_dropin()
    try:
        await systemctl("daemon-reload")
    except (OSError, RuntimeError):
        pass
    print("后台服务已停止并移除注册。")


def _linux_command_removal() -> None:
    link = _command_link()
    expected = (INSTALL_ROOT / "codex-wechat").resolve()
    try:
        owns_link = link.is_symlink() and link.resolve() == expected
    except OSError:
        owns_link = False
    if owns_link:
        link.unlink()
        print(f"已移除命令入口: {link}")
    elif link.exists():
        print(f"保留不是本安装创建的命令入口: {link}")


def _purge_linux_data() -> None:
    root = data_root()
    install = INSTALL_ROOT.resolve()
    if root == install:
        for name in LINUX_DATA_PATHS:
            _remove_path(root / name)
        print("已删除配置、登录、待办、工作目录、日志和共享后台数据。")
        return
    if install.is_relative_to(root):
        raise ValueError(f"数据目录不能包含安装目录: {root}")
    protected = {Path(root.anchor), Path.home().resolve()}
    if root in protected or Path.home().resolve().is_relative_to(root):
        raise ValueError(f"拒绝删除范围过大的数据目录: {root}")
    if not root.exists():
        print(f"数据目录不存在: {root}")
        return
    if not root.is_dir():
        raise ValueError(f"数据目录不是目录: {root}")
    for name in LINUX_DATA_PATHS:
        _remove_path(root / name)
    print(f"已删除数据目录中的用户数据: {root}")


def _require_no_bridge() -> None:
    state_dir = data_root() / ".state"
    if not state_dir.exists():
        return
    try:
        store = Store(state_dir)
    except RuntimeError:
        raise RuntimeError("前台桥接仍在运行，请先按 Ctrl+C 退出后再卸载。") from None
    except (OSError, ValueError) as error:
        raise RuntimeError(f"无法确认前台桥接是否已停止: {state_dir}") from error
    else:
        store.close()


async def uninstall(*, purge: bool = False) -> None:
    if IS_WINDOWS:
        raise RuntimeError("Windows 卸载请使用 stable uninstall.ps1；uninstall.py 仅用于 Linux。")
    # Validate the data-root contract before removing the service or touching
    # any user data. The stable entry checks this too, but a direct helper
    # invocation must not be able to skip the check.
    root = data_root()
    await _linux_service_removal()
    _require_no_bridge()
    _linux_command_removal()
    _remove_data_root_marker()
    if purge:
        _purge_linux_data()
    else:
        print(f"用户数据已保留: {root}")
        print("如需同时删除配置、登录和待办，请使用 --purge-data。")


def main(argv=None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--purge-data",
        action="store_true",
        help="同时删除配置、登录、待办、工作目录、日志和共享后台数据",
    )
    args = parser.parse_args(argv)
    try:
        asyncio.run(uninstall(purge=args.purge_data))
    except (KeyboardInterrupt, asyncio.CancelledError):
        return 130
    except (OSError, RuntimeError, ValueError) as error:
        print(f"uninstall.py: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
